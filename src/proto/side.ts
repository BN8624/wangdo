/** 식객을 고른 자리: 곁이야기 아니면 그날의 짧은 이야기 */
const pickWho = (day: number, who: 'bs' | 'mu' | 'sd', id: MemberId, to: string): Beat[] => [
  { t: 'label', name: `hub${day}_${who}` },
  { t: 'walk', to, face: 0 },
  { t: 'side', who: id, chat: `hub${day}_${who}_chat` },
];

/** 그날의 짧은 이야기: 대사 몇 줄과 작은 선택 하나 */
const chat = (day: number, who: 'bs' | 'mu' | 'sd', id: MemberId, lines: Line[], prompt: string, a: [string, number, Line[]], b: [string, number, Line[]]): Beat[] => [
  { t: 'label', name: `hub${day}_${who}_chat` },
  { t: 'talk', lines },
  {
    t: 'choice',
    id: `hub${day}_${who}`,
    prompt,
    options: [
      { text: a[0], bond: { [id]: a[1] }, reply: a[2] },
      { text: b[0], bond: { [id]: b[1] }, reply: b[2] },
    ],
  },
  { t: 'walk', to: '오두막' },
  { t: 'ret' },
];

